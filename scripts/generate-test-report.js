#!/usr/bin/env node

/**
 * Test Report Generator
 * 
 * Reads vitest JSON report and generates a human-readable markdown report
 * with test coverage summary, phase breakdown, and historical tracking.
 * 
 * Usage: node scripts/generate-test-report.js
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ROOT_DIR = path.resolve(__dirname, '..');
const REPORT_INPUT = path.join(ROOT_DIR, 'test-results', 'vitest-report.json');
const REPORT_OUTPUT = path.join(ROOT_DIR, 'test-results', 'TEST-REPORT.md');
const HISTORY_FILE = path.join(ROOT_DIR, 'test-results', 'test-history.json');

function readJSON(filePath) {
  if (!fs.existsSync(filePath)) {
    return null;
  }
  return JSON.parse(fs.readFileSync(filePath, 'utf-8'));
}

function writeFile(filePath, content) {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  fs.writeFileSync(filePath, content, 'utf-8');
}

function getCurrentDate() {
  const now = new Date();
  return now.toISOString().split('T')[0]; // YYYY-MM-DD
}

function formatDuration(ms) {
  if (ms < 1000) return `${ms}ms`;
  return `${(ms / 1000).toFixed(2)}s`;
}

function generateReport(vitestReport) {
  const { testResults, numTotalTests, numPassedTests, numFailedTests, success, startTime } = vitestReport;

  const date = getCurrentDate();
  const duration = vitestReport.testResults.reduce((sum, file) => sum + (file.duration || 0), 0);

  let report = `# Test Report\n\n`;
  report += `**Generated:** ${date}\n`;
  report += `**Duration:** ${formatDuration(duration)}\n`;
  report += `**Status:** ${success ? '✅ PASS' : '❌ FAIL'}\n\n`;

  report += `---\n\n`;
  report += `## Summary\n\n`;
  report += `| Metric | Value |\n`;
  report += `|--------|-------|\n`;
  report += `| Total Tests | ${numTotalTests} |\n`;
  report += `| Passed | ✅ ${numPassedTests} |\n`;
  report += `| Failed | ${numFailedTests > 0 ? '❌' : '✅'} ${numFailedTests} |\n`;
  report += `| Success Rate | ${((numPassedTests / numTotalTests) * 100).toFixed(1)}% |\n\n`;

  // Phase breakdown
  report += `## Phase Breakdown\n\n`;

  const phaseTests = {
    'Phase 1 (Calculation)': [],
    'Phase 3 (Calendar Export)': [],
    'Phase 5 (Social Share)': [],
    'Phase 6 (Custom Validation)': [],
    'Other': []
  };

  testResults.forEach(file => {
    const fileName = path.basename(file.name);
    let phase = 'Other';

    if (fileName.includes('Milestone.test') || fileName.includes('Card.test') || 
        fileName.includes('temporal-edge-cases') || fileName.includes('design-decisions')) {
      phase = 'Phase 1 (Calculation)';
    } else if (fileName.includes('calendarExport')) {
      phase = 'Phase 3 (Calendar Export)';
    } else if (fileName.includes('socialShare')) {
      phase = 'Phase 5 (Social Share)';
    } else if (fileName.includes('customMilestone')) {
      phase = 'Phase 6 (Custom Validation)';
    }

    const testCount = (file.assertionResults || []).length;
    const passed = (file.assertionResults || []).filter(t => t.status === 'passed').length;

    phaseTests[phase].push({
      file: fileName,
      tests: testCount,
      passed: passed,
      duration: file.duration || 0
    });
  });

  Object.entries(phaseTests).forEach(([phase, files]) => {
    if (files.length === 0) return;

    const totalTests = files.reduce((sum, f) => sum + f.tests, 0);
    const totalPassed = files.reduce((sum, f) => sum + f.passed, 0);
    const totalDuration = files.reduce((sum, f) => sum + f.duration, 0);

    report += `### ${phase}\n\n`;
    report += `**Total:** ${totalPassed}/${totalTests} passed (${formatDuration(totalDuration)})\n\n`;

    files.forEach(file => {
      const status = file.passed === file.tests ? '✅' : '❌';
      report += `- ${status} \`${file.file}\` — ${file.passed}/${file.tests} (${formatDuration(file.duration)})\n`;
    });

    report += `\n`;
  });

  // Failed tests (if any)
  if (numFailedTests > 0) {
    report += `## ❌ Failed Tests\n\n`;

    testResults.forEach(file => {
      const failed = (file.assertionResults || []).filter(t => t.status === 'failed');
      if (failed.length > 0) {
        report += `### ${path.basename(file.name)}\n\n`;
        failed.forEach(test => {
          report += `- **${test.title}**\n`;
          if (test.failureMessages && test.failureMessages.length > 0) {
            report += `  \`\`\`\n`;
            report += `  ${test.failureMessages[0].split('\n').slice(0, 5).join('\n')}\n`;
            report += `  \`\`\`\n`;
          }
        });
        report += `\n`;
      }
    });
  }

  report += `---\n\n`;
  report += `*Report generated by \`scripts/generate-test-report.js\`*\n`;

  return report;
}

function updateHistory(vitestReport) {
  const history = readJSON(HISTORY_FILE) || { runs: [] };

  const run = {
    date: getCurrentDate(),
    timestamp: new Date().toISOString(),
    total: vitestReport.numTotalTests,
    passed: vitestReport.numPassedTests,
    failed: vitestReport.numFailedTests,
    success: vitestReport.success,
    duration: vitestReport.testResults.reduce((sum, file) => sum + (file.duration || 0), 0)
  };

  history.runs.push(run);

  // Keep last 50 runs
  if (history.runs.length > 50) {
    history.runs = history.runs.slice(-50);
  }

  writeFile(HISTORY_FILE, JSON.stringify(history, null, 2));

  return history;
}

function main() {
  console.log('📊 Generating test report...\n');

  const vitestReport = readJSON(REPORT_INPUT);

  if (!vitestReport) {
    console.error(`❌ Error: Could not find vitest report at ${REPORT_INPUT}`);
    console.error('   Run "npm test" first to generate the report.\n');
    process.exit(1);
  }

  const report = generateReport(vitestReport);
  writeFile(REPORT_OUTPUT, report);

  console.log(`✅ Report generated: ${REPORT_OUTPUT}`);

  const history = updateHistory(vitestReport);
  console.log(`📈 History updated: ${history.runs.length} runs tracked\n`);

  // Print summary
  console.log('Summary:');
  console.log(`  Tests: ${vitestReport.numPassedTests}/${vitestReport.numTotalTests} passed`);
  console.log(`  Status: ${vitestReport.success ? '✅ PASS' : '❌ FAIL'}\n`);

  if (!vitestReport.success) {
    process.exit(1);
  }
}

main();
